# Time-varying channel models
def time_varying_channel_1(length):
    """Slow fading channel with smooth variations"""
    taps = np.zeros((length, num_taps), dtype=complex)
    time = np.linspace(0, 2*np.pi, length)

    # Base taps with time-varying amplitudes and phases
    taps[:, 0] = (0.8 + 0.1*np.sin(0.1*time)) * np.exp(1j*(0.5 + 0.2*np.cos(0.05*time)))
    taps[:, 1] = (0.6 + 0.1*np.cos(0.15*time)) * np.exp(1j*(0.3 + 0.1*np.sin(0.07*time)))
    taps[:, 2] = (0.4 + 0.05*np.sin(0.2*time)) * np.exp(1j*(0.1 + 0.05*np.cos(0.1*time)))
    taps[:, 3] = (0.2 + 0.05*np.cos(0.25*time)) * np.exp(1j*(-0.1 + 0.03*np.sin(0.12*time)))

    # Normalize power
    for i in range(length):
        taps[i] /= np.sqrt(np.sum(np.abs(taps[i])**2))

    return taps

def time_varying_channel_2(length):
    """Fast fading channel with more rapid variations"""
    taps = np.zeros((length, num_taps), dtype=complex)
    time = np.linspace(0, 10*np.pi, length)

    # More rapid variations
    taps[:, 0] = (0.7 + 0.2*np.sin(0.5*time)) * np.exp(1j*(0.5 + 0.3*np.cos(0.3*time)))
    taps[:, 1] = (0.5 + 0.2*np.cos(0.6*time)) * np.exp(1j*(0.3 + 0.2*np.sin(0.4*time)))
    taps[:, 2] = (0.3 + 0.1*np.sin(0.7*time)) * np.exp(1j*(0.1 + 0.1*np.cos(0.5*time)))
    taps[:, 3] = (0.2 + 0.1*np.cos(0.8*time)) * np.exp(1j*(-0.1 + 0.1*np.sin(0.6*time)))

    # Normalize power
    for i in range(length):
        taps[i] /= np.sqrt(np.sum(np.abs(taps[i])**2))

    return taps

# jakes_fading_channel

def jakes_fading_channel(length):
    """f_d: normalized Doppler frequency (e.g., 0.01–0.1)"""
    t = np.arange(length)
    taps = np.zeros((length, num_taps), dtype=complex)
    for k in range(num_taps):
        # Independent Rayleigh fading per tap
        re = np.cos(2 * np.pi * f_d * t + 2 * np.pi * np.random.rand())
        im = np.sin(2 * np.pi * f_d * t + 2 * np.pi * np.random.rand())
        fading = (re + 1j * im) / np.sqrt(2)
        taps[:, k] = fading * (1.0 / (k + 1))  # decaying power
    # Normalize
    for i in range(length):
        taps[i] /= np.linalg.norm(taps[i])
    return taps

