# QPSK mapping (Gray-coded)
def qpsk_modulation(bit_pairs):
    mapping = {
        (0, 0): (1 + 1j) / np.sqrt(2),
        (0, 1): (-1 + 1j) / np.sqrt(2),
        (1, 1): (-1 - 1j) / np.sqrt(2),
        (1, 0): (1 - 1j) / np.sqrt(2),
    }
    return np.array([mapping[tuple(bp)] for bp in bit_pairs])
